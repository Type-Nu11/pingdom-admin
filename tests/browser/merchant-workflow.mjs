import assert from 'node:assert/strict'
import { mkdtemp, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { createServer } from 'vite'
import { chromium } from 'playwright'

const output = await mkdtemp(join(tmpdir(), 'pingdom-247-'))
const server = await createServer({ envDir: false, cacheDir: join(output, 'cache'), server: { host: '127.0.0.1', port: 0, open: false }, plugins: [{ name: 'workflow-fixture', enforce: 'pre', resolveId(source) { if (source.endsWith('/map/NaverMap')) return resolve('tests/browser/place-map-fixture.jsx') }, configureServer(vite) {
  vite.middlewares.use(async (req, res, next) => {
    if (!['/merchant', '/merchant/place-registration', '/merchant/offers', '/login'].includes(req.url.split('?')[0])) return next()
    res.setHeader('Content-Type', 'text/html')
    res.end(await vite.transformIndexHtml(req.url, (await readFile('index.html', 'utf8')).replace('/src/main.tsx', '/tests/browser/merchant-workflow-fixture.jsx')))
  })
} }] })
let browser, page
try {
  await server.listen(); browser = await chromium.launch()
  const base = `http://127.0.0.1:${server.httpServer.address().port}`
  console.log(`Screenshots: ${output}`)
  for (const [width, height] of [[1920, 1080], [1366, 768], [390, 844]]) {
    page = await browser.newPage({ viewport: { width, height } })
    page.setDefaultTimeout(10000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => {
      const url = new URL(route.request().url())
      return (url.hostname === '127.0.0.1' && !url.pathname.startsWith('/api')) || ['fonts.googleapis.com', 'fonts.gstatic.com', 'cdn.jsdelivr.net'].includes(url.hostname) ? route.continue() : route.abort()
    })
    const warning = page.getByRole('dialog', { name: '저장하지 않은 변경 사항이 있습니다', exact: true })
    const registration = `${base}/merchant/place-registration`
    await page.goto(`${registration}?mode=slow`)
    await page.getByRole('status').filter({ hasText: '신청 내역을 불러오는 중입니다.' }).waitFor()
    assert.equal(await page.getByRole('button', { name: '새 장소 등록 신청', exact: true }).isDisabled(), true)
    assert.equal(await page.getByText('작성 중이거나 처리된 신규 장소 등록 신청이 없습니다.', { exact: true }).count(), 0)
    await page.getByRole('button', { name: /^합성 신청 1 / }).waitFor()
    await page.goto(registration)
    await page.getByRole('button', { name: /^합성 신청 1 / }).waitFor()
    assert.equal(await page.locator('input[type="file"]').count(), 0, 'history is the first screen, not underneath a form')
    await page.screenshot({ path: join(output, `history-${width}.png`) })
    await page.getByRole('button', { name: /^합성 신청 1 / }).focus()
    await page.keyboard.press('Enter')
    const legal = page.getByRole('textbox', { name: /법적 성명/ })
    await legal.waitFor()
    assert.equal(await page.locator('[aria-label="신청서"]').evaluate(element => element === document.activeElement), true)
    assert.equal(await legal.inputValue(), '합성 신청자')
    await legal.fill('작성 중 신청자')
    await page.getByRole('button', { name: '신청 내역 보기', exact: true }).click()
    await warning.getByRole('button', { name: '계속 작성', exact: true }).click()
    assert.equal(await legal.inputValue(), '작성 중 신청자')
    await page.getByRole('button', { name: '신청 내역 보기', exact: true }).click()
    await warning.getByRole('button', { name: '변경 버리고 이동', exact: true }).click()
    await page.getByRole('button', { name: /^합성 신청 1 / }).click()
    assert.equal(await legal.inputValue(), '합성 신청자', 'the same application can be reopened with saved values')
    await page.getByRole('button', { name: '새 장소 등록 신청', exact: true }).click()
    assert.equal(await legal.inputValue(), '', 'new applications never restore unrelated input')
    await page.locator('input[type="file"]').setInputFiles({ name: 'synthetic.pdf', mimeType: 'application/pdf', buffer: Buffer.from('synthetic') })
    await page.getByRole('button', { name: '파일 추가', exact: true }).click()
    await page.getByRole('button', { name: '신청 내역 보기', exact: true }).click()
    await warning.getByRole('button', { name: '계속 작성', exact: true }).click()
    await page.getByText('synthetic.pdf', { exact: true }).waitFor()
    await page.getByRole('button', { name: '신청 내역 보기', exact: true }).click()
    await warning.getByRole('button', { name: '변경 버리고 이동', exact: true }).click()
    await page.getByRole('tab', { name: '취소 내역 (1)', exact: true }).click()
    await page.getByRole('button', { name: /^합성 신청 30 / }).waitFor()
    assert.equal(await page.locator('input[type="file"]').count(), 0)
    await page.evaluate(() => { window.qaMode = 'detail-failure' })
    await page.getByRole('button', { name: /^합성 신청 30 / }).click()
    await page.getByRole('alert').filter({ hasText: '합성 조회 실패' }).waitFor()
    assert.equal(await legal.count(), 0, 'failed detail does not become an empty new form')

    await page.goto(`${registration}?mode=empty`)
    await page.getByText('작성 중이거나 처리된 신규 장소 등록 신청이 없습니다.', { exact: true }).waitFor()
    await page.getByRole('button', { name: '새 장소 등록 신청', exact: true }).click()
    await legal.waitFor()
    await page.goto(`${registration}?mode=failure`)
    await page.getByRole('alert').filter({ hasText: '신규 장소 등록 신청 정보를 불러오지 못했습니다.' }).waitFor()
    assert.equal(await legal.count(), 0)

    await page.goto(`${base}/merchant/offers`)
    const code = page.getByRole('textbox', { name: '쿠폰 코드', exact: true })
    await page.getByRole('button', { name: '쿠폰 사용으로 이동', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await code.evaluate(element => element === document.activeElement), true)
    await page.screenshot({ path: join(output, `coupon-${width}.png`) })
    assert.equal(await page.evaluate(() => window.qaRequests.some(request => request.method !== 'get')), false)
    await code.fill('01234567-89ab-4cde-8f01-234567890abc')
    page.once('dialog', dialog => dialog.dismiss())
    await page.getByRole('button', { name: '사용 처리', exact: true }).click()
    assert.equal(await page.evaluate(() => window.qaRequests.some(request => request.method !== 'get')), false, 'canceling final confirmation never redeems')
    await page.evaluate(() => { window.qaMode = 'redeem-failure' })
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: '사용 처리', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '합성 조회 실패' }).waitFor()
    assert.equal(await code.inputValue(), '01234567-89ab-4cde-8f01-234567890abc')
    await page.evaluate(() => { window.qaMode = 'success' })
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: '사용 처리', exact: true }).click()
    await page.getByText(/쿠폰 사용이 완료되었습니다/).waitFor()
    assert.equal(await code.inputValue(), '')
    await page.getByRole('button', { name: /^합성 혜택 1 / }).click()
    await page.getByText('저장된 혜택은 내용을 변경할 수 없습니다. 내용을 확인한 뒤 공개하세요.', { exact: true }).waitFor()
    await page.screenshot({ path: join(output, `offers-${width}.png`) })
    await page.getByRole('button', { name: /^합성 혜택 2 / }).click()
    await page.getByText('종료된 혜택입니다. 등록 내용을 확인할 수 있습니다.', { exact: true }).waitFor()
    await page.getByRole('button', { name: /^합성 혜택 3 / }).click()
    await page.getByText('공개 중인 혜택입니다. 제공을 중단하려면 혜택을 종료하세요.', { exact: true }).waitFor()
    await page.goto(`${base}/merchant/offers?mode=empty`)
    await page.getByText('등록된 혜택이 없습니다. 첫 혜택을 초안으로 등록해보세요.', { exact: true }).waitFor()
    await page.getByRole('button', { name: '쿠폰 사용으로 이동', exact: true }).click()
    assert.equal(await code.evaluate(element => element === document.activeElement), true)
    await page.goto(`${base}/merchant?count=2`)
    const nav = page.getByRole('navigation', { name: '가게 주요 업무', exact: true })
    await nav.waitFor()
    await page.getByRole('heading', { name: '전체 매장 성과', exact: true }).waitFor()
    assert.ok(await nav.evaluate(element => element.getBoundingClientRect().top) < height)
    assert.ok(await nav.evaluate(element => element.getBoundingClientRect().top) < await page.getByRole('heading', { name: '전체 매장 성과', exact: true }).evaluate(element => element.getBoundingClientRect().top))
    await page.screenshot({ path: join(output, `home-${width}.png`) })
    const introduction = page.getByRole('textbox', { name: /가게 소개/ })
    await introduction.fill('홈에서 작성 중인 소개')
    await nav.getByRole('link', { name: '혜택·쿠폰', exact: true }).click()
    await warning.getByRole('button', { name: '계속 작성', exact: true }).click()
    assert.equal(await introduction.inputValue(), '홈에서 작성 중인 소개')
    await nav.getByRole('link', { name: '혜택·쿠폰', exact: true }).click()
    await warning.getByRole('button', { name: '변경 버리고 이동', exact: true }).click()
    await page.getByRole('button', { name: '쿠폰 사용으로 이동', exact: true }).waitFor()
    await page.goto(`${base}/merchant?count=0`)
    await page.getByText('연결된 장소가 없습니다.', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.deepEqual(await page.evaluate(() => window.qaUnexpected), [])
    assert.deepEqual(errors, [])
    await page.goto(`${registration}?mode=unauthorized`)
    await page.waitForURL('**/login')
    console.log(`${width}x${height} history/detail/new, pending files, coupon navigation/confirmation, home PASS`)
    await page.close()
  }
} catch (error) {
  if (page && !page.isClosed()) { await page.screenshot({ path: join(output, 'failure.png') }); console.log(page.url(), await page.evaluate(() => window.qaRequests)) }
  throw error
} finally { await browser?.close(); await server.close() }
