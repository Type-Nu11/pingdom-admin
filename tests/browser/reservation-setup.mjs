import assert from 'node:assert/strict'
import { join } from 'node:path'
import { chromium } from 'playwright'
import { startReservationSetupServer } from './reservation-setup-server.mjs'

const { server, base, output } = await startReservationSetupServer()
let browser
try {
  browser = await chromium.launch()
  for (const [width, height] of [[1920, 1080], [1366, 768], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    const errors = [], forbidden = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', event => {
      if (event.type() !== 'error' || event.text().includes('Synthetic failure')) return
      errors.push(event.text())
    })
    await page.route('**/*', route => {
      const url = new URL(route.request().url())
      if (route.request().method() === 'GET' && route.request().resourceType() === 'stylesheet'
        && ['fonts.googleapis.com', 'cdn.jsdelivr.net'].includes(url.hostname)) return route.fulfill({ status: 200, contentType: 'text/css', body: '' })
      if (url.origin !== base || url.pathname.startsWith('/api/')) {
        forbidden.push(url.pathname)
        return route.abort()
      }
      return route.continue()
    })
    await page.goto(`${base}/merchant/reservations/products`)
    await page.getByRole('button', { name: '시간 등록', exact: true }).waitFor()
    assert.equal(new URL(page.url()).pathname, '/merchant/reservations/setup')
    await page.getByRole('status').filter({ hasText: '예약 상품 기능은 종료' }).waitFor()
    assert.equal(await page.getByRole('button', { name: '예약 상품', exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: '시간 등록', exact: true }).isEnabled(), true)
    const slot = page.getByRole('button').filter({ hasText: '예약 가능 시간 #7' })
    await slot.click()
    const capacity = page.locator('input[type="number"]').first()
    await capacity.fill('9')
    await page.getByRole('button', { name: '새 시간', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '저장하지 않은 변경 사항이 있습니다' })
    await dialog.getByRole('button', { name: '계속 작성', exact: true }).click()
    assert.equal(await capacity.inputValue(), '9')
    await page.getByLabel('합성 응답 모드').selectOption('write-failure')
    await page.getByRole('button', { name: '시간 저장', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '합성 요청 실패' }).waitFor()
    assert.equal(await capacity.inputValue(), '9')
    await page.getByLabel('합성 응답 모드').selectOption('delayed')
    await page.getByRole('button', { name: '시간 저장', exact: true }).click()
    await page.getByRole('button', { name: '저장 중', exact: true }).waitFor()
    assert.equal(await capacity.isDisabled(), true)
    await page.getByRole('status').filter({ hasText: '예약 가능 시간을 저장했습니다' }).waitFor()
    await page.getByLabel('합성 응답 모드').selectOption('success')
    await page.getByRole('button', { name: '비활성화', exact: true }).click()
    await page.getByRole('button', { name: '활성화', exact: true }).waitFor()
    await page.getByRole('button', { name: '활성화', exact: true }).click()
    await page.getByRole('button', { name: '비활성화', exact: true }).waitFor()
    await page.getByRole('button', { name: '새 시간', exact: true }).click()
    for (const [label, day] of [['예약 시작 일시', 10], ['예약 종료 일시', 11]]) {
      await page.getByRole('button', { name: new RegExp(`^${label},`) }).click()
      await page.getByRole('button', { name: '다음 달', exact: true }).click()
      const date = new Date(new Date().getFullYear(), new Date().getMonth() + 1, day)
      await page.getByRole('button', { name: `${date.getFullYear()}년 ${date.getMonth() + 1}월 ${day}일`, exact: true }).click()
      await page.getByRole('button', { name: '적용', exact: true }).click()
    }
    await capacity.fill('6')
    await page.getByRole('button', { name: '시간 등록', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '예약 가능 시간을 등록했습니다' }).waitFor()
    await page.getByLabel('합성 응답 모드').selectOption('query-failure')
    await page.getByRole('button', { name: '새로고침', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '합성 요청 실패' }).waitFor()
    assert.equal(await page.getByRole('button', { name: '시간 저장', exact: true }).isDisabled(), true)
    await page.getByLabel('합성 응답 모드').selectOption('success')
    await page.getByRole('button', { name: '시간 목록 다시 시도', exact: true }).click()
    await page.getByRole('button', { name: '시간 저장', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: '시간 저장', exact: true }).isEnabled(), true)
    await page.getByRole('button', { name: '예약 시작 일시', exact: false }).focus()
    await page.keyboard.press('Enter')
    await page.getByRole('dialog').waitFor()
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.equal(await page.getByRole('button', { name: /^예약 시작 일시,/ }).evaluate(el => el === document.activeElement), true)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    const calls = JSON.parse(await page.getByLabel('합성 요청 기록').textContent())
    assert.ok(calls.every(call => !call.url.includes('reservable-products')))
    for (const call of calls.filter(call => call.body)) assert.deepEqual(Object.keys(call.body).sort(), ['endsAt', 'placeId', 'startsAt', 'totalCapacity'])
    await page.screenshot({ path: join(output, `setup-${width}.png`), fullPage: true })
    await capacity.fill('77')
    await page.getByRole('button', { name: '합성 계정 변경', exact: true }).click()
    await page.getByRole('button', { name: '시간 등록', exact: true }).waitFor()
    assert.equal(await capacity.inputValue(), '1')
    assert.equal(await page.getByRole('dialog').count(), 0)
    await page.getByLabel('합성 응답 모드').selectOption('empty')
    await page.getByRole('button', { name: '새로고침', exact: true }).click()
    await page.getByText('등록된 예약 가능 시간이 없습니다.', { exact: true }).waitFor()
    assert.deepEqual(forbidden, [])
    assert.deepEqual(errors, [])
    await page.close()
  }
  const guest = await browser.newPage()
  await guest.route('**/*', route => new URL(route.request().url()).origin === base && !new URL(route.request().url()).pathname.startsWith('/api/') ? route.continue() : route.abort())
  await guest.goto(`${base}/merchant/reservations/products?guest=1`)
  await guest.waitForURL(`${base}/login`)
  await guest.getByRole('heading', { name: '상점주 로그인' }).waitFor()
  await guest.close()
  console.log(`PASS reservation setup: legacy redirect/guest guard/create/update/toggle/errors/draft/keyboard, 3 viewports. ${output}`)
} finally {
  await browser?.close()
  await server.close()
}
